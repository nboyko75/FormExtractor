class Translator:
    def __init__(self, language: str = "en") -> None:
        self.language = language if language in LANGUAGES else "en"

    def __call__(self, key: str, **values) -> str:
        return TRANSLATIONS[self.language][key].format(**values)

    def error(self, error: Exception) -> str:
        """Translate known application errors; retain third-party diagnostics verbatim."""
        import re

        message = str(error)
        if self.language == "en":
            return message
        if message in TRANSLATIONS[self.language].values():
            return message
        if message == "Password-protected PDFs must be unlocked before extraction":
            return self("unlock_pdf")
        for key in (
            "unlock_pdf",
            "extension_error",
            "output_overwrite",
            "supported_inputs",
            "empty_document",
            "input_missing",
            "invalid_pdf",
            "invalid_image",
            "invalid_dimensions",
            "invalid_mask",
            "areas_required",
            "no_matches",
        ):
            template = TRANSLATIONS["en"][key]
            pattern = re.escape(template)
            for field in ("name", "number"):
                pattern = pattern.replace(re.escape("{" + field + "}"), f"(?P<{field}>.+)")
            match = re.fullmatch(pattern, message, flags=re.DOTALL)
            if match:
                return self(key, **match.groupdict())
        return f"{self('details')}:\n{message}"
